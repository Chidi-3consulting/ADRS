/** Get the regulation frameworks applicable to a country code. */
function get_country_regulations(string $countryCode): array {
    return COUNTRY_REGULATION_MAP[strtoupper($countryCode)] ?? COUNTRY_REGULATION_MAP['OTHER'];
}

/** Get country regulation labels (authority, law name, audit report title). */
function get_country_regulation_labels(string $countryCode): array {
    return COUNTRY_REGULATION_LABELS[strtoupper($countryCode)] ?? COUNTRY_REGULATION_LABELS['OTHER'];
}

